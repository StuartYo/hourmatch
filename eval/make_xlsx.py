"""Builds eval/spreadsheet_baseline.xlsx from eval/spreadsheet/*.csv with live SUMPRODUCT formulas.
Run `node eval/spreadsheet_baseline.mjs` first. Usage: python -I eval/make_xlsx.py
"""
import csv
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "spreadsheet"
wb = Workbook()
wb.remove(wb.active)

readme = wb.create_sheet("README")
for line in [
    "Spreadsheet baseline for HourMatch (all companies and plants fictional; generation curves are real Taipower data).",
    "data_* sheets: one row per company per hour. matched = MIN(use, certs). old_matched = MIN(old_certs, MAX(0, use - (certs - old_certs))).",
    "claims_* sheets: claim fields as a person would read them, then SUMPRODUCT formulas give the shares and the verdict.",
    "A claim holds if claimed% x 100 <= share + 50 basis points. RE100: plants commissioned before 2011 may cover at most 15% of use.",
    "Generated by eval/make_xlsx.py; values checked against eval/results_spreadsheet.json.",
]:
    readme.append([line])

for s in ["dev", "holdout"]:
    data = list(csv.reader(open(SRC / f"data_{s}.csv", encoding="utf-8")))
    ws = wb.create_sheet(f"data_{s}")
    head = data[0]
    ws.append(head)
    num = {"day", "hour", "dow", "use", "solar", "wind", "hydro", "certs", "old_certs", "matched", "old_matched"}
    for i, row in enumerate(data[1:], start=2):
        vals = [int(v) if head[j] in num else v for j, v in enumerate(row)]
        # matched and old_matched as formulas, so the sheet shows its own work
        # columns: A company B date C day D hour E dow F use G solar H wind I hydro J certs K old_certs L matched M old_matched
        vals[head.index("matched")] = f"=MIN(F{i},J{i})"
        vals[head.index("old_matched")] = f"=MIN(K{i},MAX(0,F{i}-(J{i}-K{i})))"
        ws.append(vals)
    last = len(data)
    for c in ws[1]:
        c.font = Font(bold=True)

    q = list(csv.reader(open(SRC / f"claims_{s}.csv", encoding="utf-8")))
    ws2 = wb.create_sheet(f"claims_{s}")
    qhead = q[0]  # id text company day_from day_to hour_from hour_to weekdays_only claimed_pct basis re100 truth
    extra = ["use_kwh", "matched_kwh", "certs_kwh", "old_matched_kwh", "old_certs_kwh", "hourly_bps", "volume_bps", "share_bps", "verdict", "agrees_with_truth"]
    ws2.append(qhead + extra)
    D = f"data_{s}"
    rng = lambda col: f"{D}!${col}$2:${col}${last}"
    for r, row in enumerate(q[1:], start=2):
        vals = []
        for j, v in enumerate(row):
            k = qhead[j]
            vals.append(int(v) if k in {"day_from", "day_to", "hour_from", "hour_to", "weekdays_only", "re100"} else float(v) if k == "claimed_pct" else v)
        # C company, D day_from, E day_to, F hour_from, G hour_to, H weekdays_only, I claimed_pct, J basis, K re100, L truth
        mask = (
            f"({rng('A')}=$C{r})*({rng('C')}>=$D{r})*({rng('C')}<=$E{r})*({rng('D')}>=$F{r})*({rng('D')}<$G{r})"
            f"*((($H{r}=0)+({rng('E')}<=5))>0)"
        )
        M, N, O, P, Q, R_, S_, T, U = "M", "N", "O", "P", "Q", "R", "S", "T", "U"
        vals += [
            f"=SUMPRODUCT({mask}*{rng('F')})",  # M use
            f"=SUMPRODUCT({mask}*{rng('L')})",  # N matched
            f"=SUMPRODUCT({mask}*{rng('J')})",  # O certs
            f"=SUMPRODUCT({mask}*{rng('M')})",  # P old matched
            f"=SUMPRODUCT({mask}*{rng('K')})",  # Q old certs
            f"=INT(N{r}*10000/M{r})",  # R hourly bps
            f"=INT(O{r}*10000/M{r})",  # S volume bps
            f'=IF(K{r}=1,IF(J{r}="volume",INT((O{r}-MAX(0,Q{r}-INT(M{r}*0.15)))*10000/M{r}),INT((N{r}-MAX(0,P{r}-INT(M{r}*0.15)))*10000/M{r})),IF(J{r}="volume",S{r},R{r}))',  # T share
            f'=IF(AND(ROUND(I{r}*100,0)<=IF(J{r}="volume",S{r},R{r})+50,ROUND(I{r}*100,0)<=T{r}+50),"SUPPORTED","NOT_SUPPORTED")',  # U verdict
            f"=U{r}=L{r}",
        ]
        ws2.append(vals)
    n = len(q) - 1
    ws2.append([])
    ws2.append(["correct", f"=COUNTIF(V2:V{n + 1},TRUE)", "of", n])
    for c in ws2[1]:
        c.font = Font(bold=True)

wb.save(ROOT / "spreadsheet_baseline.xlsx")
print("wrote eval/spreadsheet_baseline.xlsx")
